"""Render results/RESULTS.md from the JSON files."""
from __future__ import annotations

import json
from pathlib import Path


def _load(out: Path, name: str) -> dict:
    return json.loads((out / f"{name}.json").read_text(encoding="utf-8"))


def _f(x, nd=3):
    return "-" if x is None else f"{x:.{nd}f}"


def _ok(b):
    return "pass" if b else "FAIL"


def render(out: Path) -> str:
    d, t, r, mo, rt = (_load(out, n) for n in ("data_quality", "training", "registry", "monitoring", "retraining"))
    L = ["# Results", "", "Generated by `python -m mlcycle.cli run-all`. Do not edit by hand.", ""]
    cfg, tot = d["config"], d["total"]
    L += ["## 1. Data quality", "",
          f"{cfg['months']} months x {cfg['rows_per_month']} rows, seed {cfg['seed']}. "
          f"Feature shift at month {cfg['feature_shift_month']}, concept shift at month {cfg['concept_shift_month']}.", "",
          f"Rows in: {tot['rows_in']}, dropped by schema checks: {tot['rows_dropped']}.", "",
          "| check | rows failing |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in tot["failures"].items()]
    L += ["", "| month | rows dropped | churn rate | mean usage_hours | mean monthly_charges |", "|---|---|---|---|---|"]
    L += [f"| {m['month']} | {m['rows_dropped']} | {m['churn_rate']:.3f} | {m['mean_usage_hours']:.1f} | "
          f"{m['mean_monthly_charges']:.1f} |" for m in d["by_month"]]
    L += ["", "## 2. Training (train months 0-4, validation month 5, test month 6)", "",
          "| model | split | AUC | PR-AUC | Brier | ECE | base rate |", "|---|---|---|---|---|---|---|"]
    for k, v in t["models"].items():
        for split in ("validation", "test"):
            s = v[split]
            L.append(f"| {k} | {split} | {_f(s['auc'])} | {_f(s['pr_auc'])} | {_f(s['brier'])} | "
                     f"{_f(s['ece'])} | {_f(s['base_rate'])} |")
    L += ["", "## 3. Registry and promotion gates (holdout month 5)", "",
          "| step | candidate | production before | AUC cand | AUC prod | gain | ECE cand | schema | beats prod | calibration | result |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in r["steps"]:
        c = s["checks"]
        before = "-" if s["production_before"] is None else f"v{s['production_before']}"
        L.append(f"| {s['step']} | v{s['candidate']} | {before} | {_f(s['candidate_auc'])} | {_f(s['production_auc'])} | "
                 f"{_f(s['auc_gain'], 4)} | {_f(s['candidate_ece'])} | {_ok(c['schema'])} | "
                 f"{_ok(c['beats_production'])} | {_ok(c['calibration'])} | {'promoted' if s['passed'] else 'rejected'} |")
    L += ["", f"Rollback restored v{r['rollback_to']}. Final production: v{r['final_production']}." if r["rollback_to"]
          else f"No rollback (nothing earlier to go back to). Final production: v{r['final_production']}.", "",
          "Audit log:", "", "| at | event | version | replaced | reason |", "|---|---|---|---|---|"]
    for e in r["audit_log"]:
        rep = e.get("replaced")
        L.append(f"| {e.get('at', '')} | {e['event']} | v{e['version']} | {'-' if rep is None else 'v' + str(rep)} | "
                 f"{e.get('reason', '')} |")
    L += ["", "## 4. Monitoring of v1 (never retrained)", "",
          "| month | max feature PSI | feature | usage_hours KS | prediction PSI | AUC on month-1 labels | alerts |",
          "|---|---|---|---|---|---|---|"]
    for m in mo["by_month"]:
        f, v = max(m["psi"].items(), key=lambda kv: kv[1])
        L.append(f"| {m['month']} | {v:.3f} | {f} | {m['ks']['usage_hours']:.3f} | {m['prediction_psi']:.3f} | "
                 f"{_f(m['lagged_auc'])} | {', '.join(m['alerts']) or '-'} |")
    L += ["", "## 5. Retraining policies", "",
          "| policy | mean AUC | AUC before concept shift | AUC after | min AUC | mean ECE | trainings | promotions | "
          "alert months | true | false | unevaluated | missed |",
          "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
    for s in rt["summary"]:
        L.append(f"| {s['policy']} | {s['mean_auc']:.3f} | {s['mean_auc_before_concept_shift']:.3f} | "
                 f"{s['mean_auc_after_concept_shift']:.3f} | {s['min_auc']:.3f} | {s['mean_ece']:.3f} | {s['trainings']} | "
                 f"{s['promotions']} | {s['alert_months']} | {s['alerts_true']} | {s['alerts_false']} | "
                 f"{s['alerts_unevaluated']} | {s['missed_degradations']} |")
    pols = list(rt["monthly"])
    L += ["", "AUC by month:", "", "| month | " + " | ".join(pols) + " |", "|---|" + "---|" * len(pols)]
    for i, row in enumerate(rt["monthly"][pols[0]]):
        cells = []
        for p in pols:
            x = rt["monthly"][p][i]
            mark = (" A" if x["alerts"] else "") + (" R" if x["promoted"] else "")
            cells.append(f"{x['auc']:.3f}{mark}")
        L.append(f"| {row['month']} | " + " | ".join(cells) + " |")
    L += ["", "A = monitoring raised an alert at the end of that month. R = a new model was promoted at the end "
          "of that month and serves from the next month."]
    return "\n".join(L) + "\n"
